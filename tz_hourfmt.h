// Returns 12 or 24. `fallback` is returned for empty/unknown names.
inline uint8_t tzHourFormatByName(const char* tzName, uint8_t fallback = 24) {
  if (!tzName || !*tzName) return fallback;
  int lo = 0, hi = TZ_HOUR_COUNT - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    int c = strcmp_P(tzName, (PGM_P)TZ_HOUR_TABLE[mid].name);
    if (c == 0) return pgm_read_byte(&TZ_HOUR_TABLE[mid].fmt);
    if (c < 0) hi = mid - 1; else lo = mid + 1;
  }
  return fallback;
}

inline uint8_t tzHourFormatByName(const String& tzName, uint8_t fallback = 24) {
  return tzHourFormatByName(tzName.c_str(), fallback);
}
